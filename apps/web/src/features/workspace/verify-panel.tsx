type StageView = { stage: number; name: string; expect: Record<string, { type: "bool"; value: boolean } | { type: "receipt" }> };

/**
 * Expected versus observed for one probe (FR-18). Expectations come from the approved claims
 * through the probe plan; observations are what Kane stored. A value that was never observed is
 * shown as such and is never counted as a match.
 */
function ExpectedObserved({ probe, pageIdentity }: { probe: ProbeView; pageIdentity: string }) {
  const latest = probe.latest;
  if (!latest) return null;
  if (probe.executor === "http") {
    const outcomes = Object.entries((latest.serverEvidence ?? {}) as Record<string, string>);
    if (outcomes.length === 0) return null;
    return (
      <table className="w-full text-left" data-testid="probe-expected-observed">
        <caption className="pb-1 text-left text-ink-muted">Server checks (no browser)</caption>
        <thead><tr className="text-ink-muted"><th scope="col" className="font-normal">Check</th><th scope="col" className="font-normal">Result</th></tr></thead>
        <tbody>
          {outcomes.map(([checkKey, outcome]) => (
            <tr key={checkKey} className="border-t border-line"><td className="py-0.5 font-mono">{checkKey}</td><td className={outcome === "PASS" ? "" : "text-fail"}>{outcome}</td></tr>
          ))}
        </tbody>
      </table>
    );
  }
  const observed = (latest.observation ?? {}) as Record<string, unknown>;
  const rows: { stage: number; key: string; expected: string; observed: string; matches: boolean | null }[] = [
    {
      stage: 0,
      key: "page_definition_hash",
      expected: pageIdentity,
      observed: observed.page_definition_hash === undefined ? "not observed" : String(observed.page_definition_hash),
      matches: observed.page_definition_hash === undefined ? null : String(observed.page_definition_hash) === pageIdentity,
    },
  ];
  for (const stage of (probe.stages ?? []) as StageView[]) {
    for (const [key, expectation] of Object.entries(stage.expect)) {
      const value = observed[key];
      const seen = value !== undefined && value !== null;
      rows.push({
        stage: stage.stage,
        key,
        expected: expectation.type === "bool" ? String(expectation.value) : "8-character receipt code",
        observed: seen ? String(value) : "not observed",
        matches: !seen ? null : expectation.type === "bool" ? String(value) === String(expectation.value) : /^[A-Z0-9]{8}$/.test(String(value)),
      });
    }
  }
  return (
    <table className="w-full text-left" data-testid="probe-expected-observed">
      <caption className="pb-1 text-left text-ink-muted">Expected (from the approved claims) and observed (by Kane)</caption>
      <thead>
        <tr className="text-ink-muted">
          <th scope="col" className="font-normal">Stage</th>
          <th scope="col" className="font-normal">Observation</th>
          <th scope="col" className="font-normal">Expected</th>
          <th scope="col" className="font-normal">Observed</th>
        </tr>
      </thead>
      <tbody>
        {rows.map((row) => (
          <tr key={`${row.stage}-${row.key}`} className="border-t border-line" data-match={row.matches === null ? "unobserved" : String(row.matches)}>
            <td className="py-0.5 font-mono">{row.stage}</td>
            <td className="font-mono">{row.key}</td>
            <td className="font-mono">{row.expected}</td>
            <td className={`font-mono ${row.matches === false ? "text-fail" : row.matches === null ? "text-unknown" : ""}`}>
              {row.observed}
              {row.matches === false ? " (differs)" : ""}
            </td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

type ReportContext = { versionNo: number; definitionHash: string; claimsHash: string | null; gate: FormState["gate"]; latestFull: boolean };

const short = (value: string | null | undefined, length = 12) => (value ? value.slice(0, length) : "—");
const when = (value: string | null) => formatDateTime(value);

/**
 * Sanitized run report (FR-18): what ran, for which exact proof identity, when, and why the
 * gate is or is not open. A run with zero executed probes can never be VERIFIED, and a
 * diagnostic run is never full proof.
 */
function RunReport({ run, context }: { run: Run; context: ReportContext }) {
  const executed = run.probes.filter((probe) => probe.latest?.status === "completed").length;
  const notRun = Math.max(run.counts.required - run.counts.pass - run.counts.fail - run.counts.unknown, 0);
  const end = run.completedAt ?? run.canceledAt;
  const seconds = end ? Math.round((Date.parse(end) - Date.parse(run.startedAt ?? run.requestedAt)) / 1000) : null;
  return (
    <section aria-label="Full verification report" className="flex flex-col gap-1">
    <h4 className="text-xs font-semibold">Full verification report</h4>
    <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1 rounded-lg border border-line px-3 py-2 text-[11px]" data-testid="run-report" data-executed={executed}>
      <dt className="text-ink-muted">Run</dt>
      <dd className="break-all font-mono">{run.id}</dd>
      <dt className="text-ink-muted">Kind</dt>
      <dd>{run.mode === "full" ? "Full suite of required probes" : "Diagnostic confirmation (never full proof)"} · {run.state}{run.detail ? ` (${run.detail})` : ""}</dd>
      <dt className="text-ink-muted">Probes</dt>
      <dd>
        {run.counts.required} required · {run.counts.pass} pass · {run.counts.fail} fail · {run.counts.unknown} unknown · {notRun} not run · {executed} executed in this run
        {executed === 0 ? " · nothing was executed, so this run cannot be verified" : ""}
      </dd>
      <dt className="text-ink-muted">Freshness</dt>
      <dd>
        {run.mode !== "full" ? "Not applicable to a diagnostic run" : run.fresh ? "Fresh for this exact version" : "Stale: the proof identity has changed since this run"}
        <span className="block break-all font-mono text-ink-muted">key {short(run.verificationKey, 24)}</span>
      </dd>
      <dt className="text-ink-muted">Identity</dt>
      <dd className="font-mono">
        v{context.versionNo} · definition {short(context.definitionHash, 8)} · claims {short(context.claimsHash, 8)} · renderer {run.rendererBuildId} · environment {run.environmentId} · policy {run.probePolicyVersion} · scenarios {short(run.scenarioSetHash, 8)}
      </dd>
      <dt className="text-ink-muted">Timeline</dt>
      <dd suppressHydrationWarning>
        requested {when(run.requestedAt)} · started {when(run.startedAt)} · {run.canceledAt ? `canceled ${when(run.canceledAt)}` : `finished ${when(run.completedAt)}`}
        {seconds !== null ? ` · ${seconds} s` : ""}
      </dd>
      <dt className="text-ink-muted">Evidence</dt>
      <dd data-testid="evidence-note">
        Sanitized. Each probe below shows its Kane run ID, the SHA-256 digest of its sealed evidence pack, and NIARVA&apos;s typed observations. The sealed pack itself stays private on the worker machine, because it can contain the token-scoped preview URL; it holds step records, screenshots, and run summaries, and no video. This report is a redacted derivative: it does not carry the pack&apos;s sealed integrity, so check a pack against its digest.
      </dd>
      <dt className="text-ink-muted">Reuse</dt>
      <dd>Every result in this report was produced by this run. Reusing an earlier proof never creates a run, and never counts toward recovery after a failure.</dd>
      {context.latestFull ? (
        <>
          <dt className="text-ink-muted">Gate</dt>
          <dd>{context.gate.eligible ? "Open for this version" : context.gate.reasonTexts.join(" ")}</dd>
          <dt className="text-ink-muted">Instability</dt>
          <dd>
            {context.gate.instability.unstable
              ? `After a failed run, ${context.gate.instability.required} consecutive fresh verified runs are required (${context.gate.instability.consecutiveVerifiedAfterFailure} so far).`
              : "No failed full run for this version."}
          </dd>
        </>
      ) : null}
    </dl>
    </section>
  );
}
